class TestPrepareTmuxAttach:
    def test_renders_conf_and_returns_attach_argv(self, fake_proc):
        mux = TmuxMux()
        cmd, ensure_session = session.prepare_tmux_attach(
            "s", mux=mux, hive="/opt/hive", settings=_settings()
        )
        del ensure_session
        conf_path = paths.layouts_dir() / "s" / "tmux.conf"
        assert conf_path.is_file()
        assert conf_path.read_text().startswith("# generated by hive")
        assert cmd == [
            "tmux",
            "-L",
            "hive",
            "-f",
            str(conf_path),
            "attach-session",
            "-t",
            "s",
        ]

    def test_ensure_session_bootstraps_when_absent(self, fake_proc):
        mux = TmuxMux()
        _cmd, ensure_session = session.prepare_tmux_attach(
            "s", mux=mux, hive="/opt/hive", settings=_settings()
        )
        conf_path = str(paths.layouts_dir() / "s" / "tmux.conf")
        fake_proc.script(
            ("tmux", "-L", "hive", "-f", conf_path, "has-session"), returncode=1
        )
        fake_proc.script(
            ("tmux", "-L", "hive", "-f", conf_path, "new-session"), stdout="@0\n"
        )
        ensure_session()
        assert (
            fake_proc.count("tmux", "-L", "hive", "-f", conf_path, "new-session") == 1
        )

    def test_ensure_session_is_a_noop_when_already_running(self, fake_proc):
        mux = TmuxMux()
        _cmd, ensure_session = session.prepare_tmux_attach(
            "s", mux=mux, hive="/opt/hive", settings=_settings()
        )
        conf_path = str(paths.layouts_dir() / "s" / "tmux.conf")
        fake_proc.script(
            ("tmux", "-L", "hive", "-f", conf_path, "has-session"), returncode=0
        )
        ensure_session()
        assert (
            fake_proc.count("tmux", "-L", "hive", "-f", conf_path, "new-session") == 0
        )

    def test_non_agent_layout_raises(self):
        mux = TmuxMux()
        settings = HiveSettings(zellij=ZellijConfig(layout="agent-16"))
        with pytest.raises(HiveError):
            session.prepare_tmux_attach(
                "s", mux=mux, hive="/opt/hive", settings=settings
            )


