def _start(mux, name):
    with patch("hive_cli.services.session.os.execvpe") as execvpe:
        session.start(
            ["zellij", "attach", "--create", name],
            {},
            session=name,
            mux=mux,
            restart=False,
            restart_delay=0,
            on_restart=lambda: None,
            on_stop=lambda: None,
        )
    execvpe.assert_called_once()


